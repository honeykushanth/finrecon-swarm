# state_schema.py
from typing import TypedDict, List, Dict, Any

class AgentState(TypedDict):
    """
    The global state dictionary that tracks the swarm's progress.
    Every agent will read from and append to this state.
    """
    target_domain: str
    target_asn: str
    
    # OSINT Mapper Data
    discovered_subdomains: List[str]
    resolved_ips: List[str]
    
    # Infrastructure Profiler Data (Format: {"8.8.8.8": {"ports": [80, 443], "cpes": ["cpe:/a:apache:http_server:2.4.49"]}})
    infrastructure_map: Dict[str, Dict[str, Any]]
    
    # Vulnerability Analyst Data (List of discovered CVEs and their Compliance Impact)
    cve_findings: List[Dict[str, str]]
    
    # Final String Output generated by the Report Synthesizer
    final_markdown_report: str
    
    # Error handling and failover tracking
    errors: List[str]
